// Paul2013FeatureView expands a class key for the observed feature-view
// ranking modes 1 and 2. Other values mean no supported view and fail.
func (context Context) Paul2013FeatureView(mode byte) ([10]byte, error) {
	return Paul2013FeatureViewForKey(context.Paul2013SelectionKey(), mode)
}

// Paul2013FeatureViewForKey expands a five-byte selection key using one of the
// two observed ranking projections.
func Paul2013FeatureViewForKey(key [5]byte, mode byte) ([10]byte, error) {
	flags := key[3]
	upperBoundary := flags&0x80 != 0 && (flags>>3)&7 >= 2
	lowerBoundary := flags&0x40 != 0 && flags&7 >= 2
	var view [10]byte
	switch mode {
	case 1:
		view = [10]byte{0, key[4], key[1], paul2013ClassMap[key[0]], boolByte(upperBoundary), paul2013PrimaryCategoryMap[key[0]], ((flags>>3)&7)*10 + boolByte(lowerBoundary), key[0], (flags >> 3) & 7, paul2013ClassMap[key[2]]}
	case 2:
		view = [10]byte{1, key[4], key[1], paul2013ClassMap[key[2]], boolByte(lowerBoundary), paul2013SecondaryCategoryMap[key[2]], (flags&7)*10 + boolByte(upperBoundary), key[2], flags & 7, paul2013ClassMap[key[0]]}
	default:
		return [10]byte{}, fmt.Errorf("unsupported Paul 2013 feature view mode %d", mode)
	}
	return view, nil
}

func boolByte(value bool) byte {
	if value {
		return 1
	}
	return 0
}

// Paul2013KeyMismatchWeight returns the recovered penalty for one differing
// five-byte selection-key position.
func Paul2013KeyMismatchWeight(position int) (int32, bool) {
	if position < 0 || position >= len(paul2013KeyMismatchWeights) {
		return 0, false
	}
	return paul2013KeyMismatchWeights[position], true
}

// Paul2013ViewMismatchWeight returns the recovered penalty for one differing
// position in the expanded ten-byte view.
func Paul2013ViewMismatchWeight(position int) (int32, bool) {
	if position < 0 || position >= len(paul2013ViewMismatchWeights) {
		return 0, false
	}
	return paul2013ViewMismatchWeights[position], true
}

// The mismatch penalties are read from vt_pau.dll offsets 0x7bf14 and
// 0x7bf28, respectively.
var paul2013KeyMismatchWeights = [5]int32{40, 1, 40, 10, 1000}
var paul2013ViewMismatchWeights = [10]int32{50000, 20000, 10000, 5000, 1000, 2000, 500, 100, 50, 20}
